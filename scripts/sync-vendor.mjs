#!/usr/bin/env node
/**
 * Copy Bootstrap, Font Awesome, and Kodchasan from node_modules → vendor/ for Hostinger ship.
 * Run: npm run vendor:sync (after npm install in sites/portfolio).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname( fileURLToPath( import.meta.url ) );
const root = path.join( __dirname, '..' );
const vendor = path.join( root, 'vendor' );

function rmDir( dir ) {
	if ( fs.existsSync( dir ) ) {
		fs.rmSync( dir, { recursive: true, force: true } );
	}
}

function ensureDir( dir ) {
	fs.mkdirSync( dir, { recursive: true } );
}

function copyFile( src, dest ) {
	ensureDir( path.dirname( dest ) );
	fs.copyFileSync( src, dest );
}

function copyDir( srcDir, destDir ) {
	if ( !fs.existsSync( srcDir ) ) {
		throw new Error( `Missing source dir: ${srcDir}` );
	}
	ensureDir( destDir );
	for ( const entry of fs.readdirSync( srcDir, { withFileTypes: true } ) ) {
		const src = path.join( srcDir, entry.name );
		const dest = path.join( destDir, entry.name );
		if ( entry.isDirectory() ) {
			copyDir( src, dest );
		} else {
			copyFile( src, dest );
		}
	}
}

const nm = path.join( root, 'node_modules' );
if ( !fs.existsSync( nm ) ) {
	console.error( 'Run npm install in sites/portfolio first.' );
	process.exit( 1 );
}

rmDir( vendor );
ensureDir( vendor );

// Bootstrap 5.3.3
copyFile(
	path.join( nm, 'bootstrap/dist/css/bootstrap.min.css' ),
	path.join( vendor, 'bootstrap/css/bootstrap.min.css' )
);
copyFile(
	path.join( nm, 'bootstrap/dist/js/bootstrap.bundle.min.js' ),
	path.join( vendor, 'bootstrap/js/bootstrap.bundle.min.js' )
);

// Font Awesome 6.5.1 — css + webfonts (paths in CSS are ../webfonts/)
copyDir(
	path.join( nm, '@fortawesome/fontawesome-free/css' ),
	path.join( vendor, 'fontawesome/css' )
);
copyDir(
	path.join( nm, '@fortawesome/fontawesome-free/webfonts' ),
	path.join( vendor, 'fontawesome/webfonts' )
);

// Kodchasan 400 + 700 — subset woff2 only
const kodDest = path.join( vendor, 'fonts/kodchasan' );
ensureDir( kodDest );
const kodSrc = path.join( nm, '@fontsource/kodchasan/files' );
for ( const weight of [ '400', '700' ] ) {
	const name = `kodchasan-latin-${weight}-normal.woff2`;
	copyFile( path.join( kodSrc, name ), path.join( kodDest, name ) );
}

const kodCss = `/* Self-hosted Kodchasan — generated by scripts/sync-vendor.mjs */
@font-face {
  font-family: 'Kodchasan';
  font-style: normal;
  font-display: swap;
  font-weight: 400;
  src: url('./kodchasan-latin-400-normal.woff2') format('woff2');
}
@font-face {
  font-family: 'Kodchasan';
  font-style: normal;
  font-display: swap;
  font-weight: 700;
  src: url('./kodchasan-latin-700-normal.woff2') format('woff2');
}
`;
fs.writeFileSync( path.join( kodDest, 'kodchasan.css' ), kodCss, 'utf8' );

// Inter 400 / 500 / 600 — admin UI
const interDest = path.join( vendor, 'fonts/inter' );
ensureDir( interDest );
const interSrc = path.join( nm, '@fontsource/inter/files' );
for ( const weight of [ '400', '500', '600' ] ) {
	const name = `inter-latin-${weight}-normal.woff2`;
	copyFile( path.join( interSrc, name ), path.join( interDest, name ) );
}
const interCss = `/* Self-hosted Inter — generated by scripts/sync-vendor.mjs */
@font-face {
  font-family: 'Inter';
  font-style: normal;
  font-display: swap;
  font-weight: 400;
  src: url('./inter-latin-400-normal.woff2') format('woff2');
}
@font-face {
  font-family: 'Inter';
  font-style: normal;
  font-display: swap;
  font-weight: 500;
  src: url('./inter-latin-500-normal.woff2') format('woff2');
}
@font-face {
  font-family: 'Inter';
  font-style: normal;
  font-display: swap;
  font-weight: 600;
  src: url('./inter-latin-600-normal.woff2') format('woff2');
}
`;
fs.writeFileSync( path.join( interDest, 'inter.css' ), interCss, 'utf8' );

// TinyMCE 7 — full package for base_url self-host
copyDir( path.join( nm, 'tinymce' ), path.join( vendor, 'tinymce' ) );

// Version stamp for cache busting in PHP
const manifest = {
	generatedAt: new Date().toISOString(),
	bootstrap: '5.3.3',
	fontawesome: '6.5.1',
	kodchasan: '5.2.5',
	inter: '5.2.5',
	tinymce: '^7.6.0',
};
fs.writeFileSync(
	path.join( vendor, 'manifest.json' ),
	JSON.stringify( manifest, null, 2 ) + '\n',
	'utf8'
);

console.log( 'vendor/ synced OK' );
